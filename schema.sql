-- Turmas ativas com vagas restantes (respeitando também o limite geral).
drop function if exists public.turmas_disponiveis();
create function public.turmas_disponiveis()
returns table (id text, nome text, valor numeric, restantes int, restantes_geral int, data_inicio date, idade_min int, idade_max int)
language sql stable security definer set search_path = public
as $$
  with geral as (
    select c.vagas_total - (select count(*) from public.inscricoes where not cancelada) as livre,
           c.data_inicio, c.idade_min, c.idade_max
    from public.configuracao c where c.id = 1
  )
  select t.id, t.nome, t.valor,
         greatest(least(t.vagas - (select count(*) from public.inscricoes i
                                    where i.turma = t.id and not i.cancelada), g.livre), 0)::int,
         greatest(g.livre, 0)::int,
         g.data_inicio, g.idade_min, g.idade_max
  from public.turmas t cross join geral g
  where t.ativa
  order by t.ordem, t.nome;
$$;

-- Cria uma inscrição. Valor, vagas, idade, aceite e comprovante são conferidos aqui, no banco.
-- PIX: o comprovante é obrigatório e já vira um pagamento confirmado (decisão de 11/11/2026).
-- Cartão: a inscrição fica "Contato pendente" até a equipe registrar o pagamento.
create or replace function public.criar_inscricao(dados jsonb)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v_turma    public.turmas%rowtype;
  v_cfg      public.configuracao%rowtype;
  v_ocupadas int;
  v_nasc     date;
  v_idade    int;
  v_tel      text := regexp_replace(coalesce(dados->>'responsavel_telefone', ''), '\D', '', 'g');
  v_forma    text := dados->>'forma_pagamento';
  v_comp     text := coalesce(dados->>'comprovante', '');
  v_id       bigint;
begin
  if coalesce(trim(dados->>'aluno_nome'), '') = '' then
    raise exception 'Preencha o campo: nome do aluno.';
  end if;
  if coalesce(dados->>'aluno_nascimento', '') !~ '^\d{4}-\d{2}-\d{2}$' then
    raise exception 'Preencha o campo: data de nascimento.';
  end if;
  if coalesce(trim(dados->>'responsavel_nome'), '') = '' then
    raise exception 'Preencha o campo: nome do responsável.';
  end if;
  if length(v_tel) not between 10 and 13 then
    raise exception 'Telefone inválido (inclua o DDD).';
  end if;
  if v_forma is null or v_forma not in ('PIX', 'Cartão') then
    raise exception 'Escolha a forma de pagamento.';
  end if;
  if v_forma = 'PIX' and not public.comprovante_valido(v_comp) then
    raise exception 'Anexe o comprovante do PIX.';
  end if;
  if coalesce((dados->>'consentimento')::boolean, false) is not true then
    raise exception 'Para concluir, o responsável legal precisa aceitar o Aviso de Privacidade.';
  end if;

  -- trava a configuração: serializa inscrições simultâneas para não estourar o limite geral
  select * into v_cfg from public.configuracao where id = 1 for update;

  v_nasc  := (dados->>'aluno_nascimento')::date;
  v_idade := extract(year from age(v_cfg.data_inicio, v_nasc))::int;
  if v_idade < v_cfg.idade_min or v_idade > v_cfg.idade_max then
    raise exception 'A colônia é para crianças de % a % anos (idade em %).',
      v_cfg.idade_min, v_cfg.idade_max, to_char(v_cfg.data_inicio, 'DD/MM/YYYY');
  end if;

  select * into v_turma from public.turmas where id = dados->>'turma' and ativa;
  if not found then
    raise exception 'Escolha uma turma válida.';
  end if;

  if (select count(*) from public.inscricoes where not cancelada) >= v_cfg.vagas_total then
    raise exception 'As vagas da pré-venda esgotaram.';
  end if;
  select count(*) into v_ocupadas from public.inscricoes where turma = v_turma.id and not cancelada;
  if v_ocupadas >= v_turma.vagas then
    raise exception 'Essa turma está lotada.';
  end if;

  insert into public.inscricoes (
    aluno_nome, aluno_nascimento, aluno_escola, aluno_saude,
    responsavel_nome, responsavel_cpf, responsavel_telefone, responsavel_email,
    contato_emergencia, turma, valor, autoriza_imagem, consentimento_em, versao_aviso, forma_pagamento
  ) values (
    left(trim(dados->>'aluno_nome'), 150),
    v_nasc,
    nullif(left(trim(coalesce(dados->>'aluno_escola', '')), 150), ''),
    nullif(left(trim(coalesce(dados->>'aluno_saude', '')), 1000), ''),
    left(trim(dados->>'responsavel_nome'), 150),
    nullif(left(regexp_replace(coalesce(dados->>'responsavel_cpf', ''), '\D', '', 'g'), 11), ''),
    v_tel,
    nullif(left(trim(coalesce(dados->>'responsavel_email', '')), 150), ''),
    nullif(left(trim(coalesce(dados->>'contato_emergencia', '')), 200), ''),
    v_turma.id,
    v_turma.valor,
    coalesce((dados->>'autoriza_imagem')::boolean, false),
    now(),
    left(coalesce(dados->>'versao_aviso', ''), 20),
    v_forma
  ) returning id into v_id;

  if v_forma = 'PIX' then
    insert into public.pagamentos (inscricao_id, valor, forma, data_pagamento, informado_por, confirmado, comprovante)
    values (v_id, v_turma.valor, 'PIX', (now() at time zone 'America/Sao_Paulo')::date, 'responsavel', true, v_comp);
  end if;

  return jsonb_build_object(
    'id', v_id,
    'aluno_nome', trim(dados->>'aluno_nome'),
    'turma_nome', v_turma.nome,
    'valor', v_turma.valor,
    'forma_pagamento', v_forma,
    'responsavel_telefone', v_tel
  );
end;
$$;

-- Consulta feita pelo responsável: precisa do nº da inscrição + telefone.
-- Devolve só o necessário (sem CPF, saúde etc.).
create or replace function public.consultar_inscricao(p_id bigint, p_telefone text)
returns jsonb
language plpgsql stable security definer set search_path = public
as $$
declare
  r public.inscricoes_detalhe%rowtype;
begin
  select * into r from public.inscricoes_detalhe
  where id = p_id
    and responsavel_telefone = regexp_replace(coalesce(p_telefone, ''), '\D', '', 'g');
  if not found then
    raise exception 'Inscrição não encontrada. Confira o número e o telefone.';
  end if;

  return jsonb_build_object(
    'id', r.id,
    'aluno_nome', r.aluno_nome,
    'turma_nome', r.turma_nome,
    'valor', r.valor,
    'valor_pago', r.valor_pago,
    'saldo', r.saldo,
    'status', r.status,
    'forma_pagamento', r.forma_pagamento,
    'responsavel_telefone', r.responsavel_telefone,
    'pagamentos', coalesce((
      select jsonb_agg(jsonb_build_object(
               'data_pagamento', p.data_pagamento, 'valor', p.valor, 'forma', p.forma,
               'confirmado', p.confirmado, 'com_comprovante', p.comprovante is not null) order by p.id)
      from public.pagamentos p where p.inscricao_id = r.id), '[]'::jsonb)
  );
end;
$$;

-- Responsável envia outro comprovante de PIX depois da inscrição (já entra confirmado).
drop function if exists public.informar_pagamento(bigint, text, numeric, text, date, text);
create or replace function public.informar_pagamento(
  p_id bigint, p_telefone text, p_valor numeric, p_comprovante text, p_observacao text
)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  v_insc public.inscricoes%rowtype;
begin
  select * into v_insc from public.inscricoes
  where id = p_id
    and responsavel_telefone = regexp_replace(coalesce(p_telefone, ''), '\D', '', 'g');
  if not found then
    raise exception 'Inscrição não encontrada.';
  end if;
  if v_insc.cancelada then
    raise exception 'Esta inscrição foi cancelada.';
  end if;
  if p_valor is null or p_valor <= 0 or p_valor > v_insc.valor * 2 then
    raise exception 'Informe um valor de pagamento válido.';
  end if;
  if not public.comprovante_valido(coalesce(p_comprovante, '')) then
    raise exception 'Anexe o comprovante do PIX.';
  end if;
  -- evita que alguém encha a inscrição de avisos falsos
  if (select count(*) from public.pagamentos where inscricao_id = p_id and not confirmado) >= 5 then
    raise exception 'Já existem pagamentos aguardando confirmação. Aguarde a equipe conferir.';
  end if;

  insert into public.pagamentos (inscricao_id, valor, forma, data_pagamento, observacao, informado_por, confirmado, comprovante)
  values (p_id, p_valor, 'PIX', (now() at time zone 'America/Sao_Paulo')::date,
          nullif(left(trim(coalesce(p_observacao, '')), 300), ''), 'responsavel', true, p_comprovante);
end;
$$;

-- ---------------------------------------------------------------------
-- LGPD: atende pedido de exclusão (art. 18, VI). Apaga os dados pessoais
-- e mantém só turma, valor e pagamentos (registro financeiro).
-- Os arquivos de comprovante são apagados pelo painel antes de chamar esta função.
-- ---------------------------------------------------------------------
create or replace function public.anonimizar_inscricao(p_id bigint)
returns void
language plpgsql security definer set search_path = public
as $$
begin
  if not public.eh_admin() then
    raise exception 'Sem permissão.';
  end if;
  update public.inscricoes set
    aluno_nome = 'Dados removidos (LGPD)',
    aluno_nascimento = null,
    aluno_escola = null,
    aluno_saude = null,
    responsavel_nome = 'Dados removidos (LGPD)',
    responsavel_cpf = null,
    responsavel_telefone = null,
    responsavel_email = null,
    contato_emergencia = null,
    autoriza_imagem = false,
    anonimizada_em = now()
  where id = p_id;
  update public.pagamentos set observacao = null, comprovante = null where inscricao_id = p_id;
end;
$$;

