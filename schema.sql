create table if not exists public.turmas (
  id     text primary key,
  nome   text not null,
  valor  numeric(10,2) not null check (valor >= 0),
  vagas  int not null check (vagas >= 0),
  ordem  int not null default 0,
  ativa  boolean not null default true
);

create table if not exists public.inscricoes (
  id                   bigint generated by default as identity primary key,
  criado_em            timestamptz not null default now(),
  aluno_nome           text not null,
  aluno_nascimento     date,                   -- vazio só após anonimização
  aluno_escola         text,
  aluno_saude          text,
  responsavel_nome     text not null,
  responsavel_cpf      text,
  responsavel_telefone text,                   -- só dígitos; vazio só após anonimização
  responsavel_email    text,
  contato_emergencia   text,
  turma                text not null references public.turmas(id),
  valor                numeric(10,2) not null, -- copiado da turma no momento da inscrição
  autoriza_imagem      boolean not null default false,
  cancelada            boolean not null default false
);
-- Colunas adicionadas depois (para bancos criados com versões anteriores deste arquivo)
alter table public.inscricoes
  add column if not exists consentimento_em timestamptz,  -- LGPD: quando o responsável aceitou o aviso
  add column if not exists versao_aviso     text,         -- LGPD: qual versão do aviso foi aceita
  add column if not exists anonimizada_em   timestamptz,  -- LGPD: quando os dados pessoais foram apagados
  add column if not exists forma_pagamento  text check (forma_pagamento in ('PIX', 'Cartão'));

create table if not exists public.pagamentos (
  id             bigint generated by default as identity primary key,
  inscricao_id   bigint not null references public.inscricoes(id) on delete cascade,
  criado_em      timestamptz not null default now(),
  valor          numeric(10,2) not null check (valor > 0),
  forma          text not null check (forma in ('PIX','Dinheiro','Cartão de crédito','Cartão de débito','Transferência','Boleto')),
  data_pagamento date not null,
  observacao     text,
  informado_por  text not null check (informado_por in ('responsavel','admin')),
  confirmado     boolean not null default false
);
alter table public.pagamentos
  add column if not exists comprovante text unique;   -- caminho do arquivo no Storage (bucket comprovantes)
create index if not exists pagamentos_inscricao_idx on public.pagamentos(inscricao_id);

-- Usuários (do Supabase Auth) que podem acessar o painel administrativo.
create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);

-- Configuração geral do evento (uma linha só): limite total de vagas,
-- data de início e faixa de idade (calculada na data de início).
create table if not exists public.configuracao (
  id          int primary key default 1 check (id = 1),
  vagas_total int  not null check (vagas_total >= 0),
  data_inicio date not null,
  idade_min   int  not null,
  idade_max   int  not null
);

