-- ---------------------------------------------------------------------
-- Verifica se o usuário logado é administrador
-- ---------------------------------------------------------------------
create or replace function public.eh_admin()
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

-- ---------------------------------------------------------------------
-- Visão com situação do pagamento calculada (usada pelo painel)
-- security_invoker: respeita as permissões de quem consulta.
-- ---------------------------------------------------------------------
create or replace view public.inscricoes_detalhe
with (security_invoker = true) as
select
  i.*,
  t.nome as turma_nome,
  coalesce(p.pago, 0) as valor_pago,
  greatest(i.valor - coalesce(p.pago, 0), 0) as saldo,
  case
    when i.cancelada                    then 'Cancelada'
    when coalesce(p.pago, 0) >= i.valor then 'Pago'
    when coalesce(p.pendentes, 0) > 0   then 'Aguardando confirmação'
    when coalesce(p.pago, 0) > 0        then 'Parcial'
    else 'Pendente'
  end as status
from public.inscricoes i
join public.turmas t on t.id = i.turma
left join lateral (
  select sum(valor) filter (where confirmado) as pago,
         count(*)   filter (where not confirmado) as pendentes
  from public.pagamentos
  where inscricao_id = i.id
) p on true;

-- ---------------------------------------------------------------------
-- Segurança (Row Level Security)
-- Visitantes NÃO leem nem gravam nas tabelas diretamente: só pelas
-- funções abaixo. Administradores têm acesso total.
-- ---------------------------------------------------------------------
alter table public.turmas     enable row level security;
alter table public.inscricoes enable row level security;
alter table public.pagamentos enable row level security;
alter table public.admins     enable row level security;
alter table public.configuracao enable row level security;

drop policy if exists "configuracao: admin" on public.configuracao;
create policy "configuracao: admin" on public.configuracao
  for all to authenticated using (public.eh_admin()) with check (public.eh_admin());

drop policy if exists "turmas: leitura publica" on public.turmas;
create policy "turmas: leitura publica" on public.turmas
  for select to anon, authenticated using (true);

drop policy if exists "turmas: admin" on public.turmas;
create policy "turmas: admin" on public.turmas
  for all to authenticated using (public.eh_admin()) with check (public.eh_admin());

drop policy if exists "inscricoes: admin" on public.inscricoes;
create policy "inscricoes: admin" on public.inscricoes
  for all to authenticated using (public.eh_admin()) with check (public.eh_admin());

drop policy if exists "pagamentos: admin" on public.pagamentos;
create policy "pagamentos: admin" on public.pagamentos
  for all to authenticated using (public.eh_admin()) with check (public.eh_admin());

drop policy if exists "admins: admin le" on public.admins;
create policy "admins: admin le" on public.admins
  for select to authenticated using (public.eh_admin());

-- Permissões explícitas (o RLS acima decide quais linhas cada um vê).
grant usage on schema public to anon, authenticated;
