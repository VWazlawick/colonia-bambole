-- Confere se o comprovante foi mesmo enviado e ainda não foi usado em outro pagamento.
create or replace function public.comprovante_valido(p_path text)
returns boolean
language sql stable security definer set search_path = public
as $$
  select p_path ~ '^pix/[0-9a-f-]{36}\.(jpg|jpeg|png|webp|heic|heif|pdf)$'
     and exists (select 1 from storage.objects o where o.bucket_id = 'comprovantes' and o.name = p_path)
     and not exists (select 1 from public.pagamentos p where p.comprovante = p_path);
$$;
revoke execute on function public.comprovante_valido(text) from public, anon, authenticated;

